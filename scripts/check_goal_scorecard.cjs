function read(relativePath) {
  return readFileSync(join(root, relativePath), "utf8");
}

function requireIncludes(source, relativePath, label, needles) {
  for (const needle of needles) {
    if (!source.includes(needle)) {
      errors.push(`${relativePath} must keep ${label}: ${needle}`);
    }
  }
}

function requireOrdered(source, relativePath, label, needles) {
  let cursor = -1;
  for (const needle of needles) {
    const index = source.indexOf(needle);
    if (index === -1) {
      errors.push(`${relativePath} must keep ${label}: ${needle}`);
      continue;
    }
    if (index < cursor) {
      errors.push(`${relativePath} must keep ${label} in order: ${needles.join(" -> ")}`);
      return;
    }
    cursor = index;
  }
}

function requirePercentAtLeast(line, relativePath, label, metric, floor) {
  const escapedMetric = metric.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const match = line.match(new RegExp(`${escapedMetric}=[^;]*?([0-9]+(?:\\.[0-9]+)?)%`));
  if (!match) {
    errors.push(`${relativePath} must keep ${label}: missing ${metric} percentage`);
    return;
  }
  const value = Number(match[1]);
  if (!Number.isFinite(value) || value < floor) {
    errors.push(`${relativePath} must keep ${label}: ${metric} ${value}% below ${floor}%`);
  }
}

function requirePattern(source, relativePath, label, pattern) {
  if (!pattern.test(source)) {
    errors.push(`${relativePath} must keep ${label}: ${pattern}`);
  }
}

